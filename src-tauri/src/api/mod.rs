//! The UI contract: commands, events, types and error codes.
//! Documented in `docs/SPEC.md`; TypeScript generated into `src/api/bindings.ts`.

pub mod commands;
pub mod error;
pub mod events;
pub mod types;

use tauri_specta::{collect_commands, collect_events, Builder};

/// Must equal the version at the top of `docs/SPEC.md` (checked by a test).
pub const SPEC_VERSION: &str = "1.4.1";

/// Path of the generated bindings, relative to the `src-tauri` crate root.
pub const BINDINGS_PATH: &str = "../src/api/bindings.ts";

pub fn specta_builder() -> Builder<tauri::Wry> {
    use commands::*;
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            list_nodes,
            import_links,
            import_from_clipboard,
            import_qr_image,
            add_node_manual,
            update_node,
            delete_node,
            reorder_nodes,
            select_node,
            test_node,
            connect,
            disconnect,
            get_status,
            set_capture_mode,
            set_routing_mode,
            set_dns_profile,
            get_failover_settings,
            set_failover_settings,
            get_safety_settings,
            set_safety_settings,
            get_rules_status,
            update_rules_now,
            get_helper_status,
            install_helper,
            uninstall_helper,
            get_settings,
            set_settings,
            get_logs,
            export_diagnostics,
            restore_networking,
            get_app_info,
            quit_app,
            hide_popover,
            open_settings,
            reveal_diagnostics,
        ])
        .events(collect_events![
            events::StatusChanged,
            events::ActiveNodeChanged,
            events::FailoverEvent,
            events::TrafficStatsUpdated,
            events::HealthCheck,
            events::RulesUpdated,
            events::HelperStatusChanged,
            events::NodesChanged,
            events::RecoveryCompleted,
            events::RestoreReportChanged,
            events::ErrorRaised,
            events::SettingsSectionRequested,
            events::PopoverShown,
            events::PopoverHidden,
        ])
        .typ::<error::ErrorCode>()
        .constant("SPEC_VERSION", SPEC_VERSION)
}

pub fn render_bindings(path: &std::path::Path) {
    specta_builder()
        .export(
            specta_typescript::Typescript::default()
                .header("// GENERATED by src-tauri (tauri-specta). DO NOT EDIT.\n// Regenerate: npm run gen:bindings\n"),
            path,
        )
        .expect("failed to export TypeScript bindings");
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn committed() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(BINDINGS_PATH)
    }

    /// `UPDATE_BINDINGS=1 cargo test -p edge-app bindings` rewrites the file;
    /// otherwise this fails if the committed bindings are stale.
    #[test]
    fn bindings_are_current() {
        if std::env::var_os("UPDATE_BINDINGS").is_some() {
            render_bindings(&committed());
            return;
        }
        let tmp = std::env::temp_dir().join(format!("edge-bindings-{}.ts", std::process::id()));
        render_bindings(&tmp);
        let fresh = std::fs::read_to_string(&tmp).unwrap();
        let _ = std::fs::remove_file(&tmp);
        let current = std::fs::read_to_string(committed()).unwrap_or_default();
        // A Windows checkout may have CRLF line endings (git autocrlf).
        let (fresh, current) = (fresh.replace("\r\n", "\n"), current.replace("\r\n", "\n"));
        if let Some((i, (f, c))) = fresh.lines().zip(current.lines()).enumerate().find(|(_, (f, c))| f != c) {
            panic!("src/api/bindings.ts is stale: run `npm run gen:bindings` (line {}: generated {f:?}, committed {c:?})", i + 1);
        }
        assert!(fresh == current, "src/api/bindings.ts is stale: run `npm run gen:bindings` (length differs)");
    }

    #[test]
    fn spec_md_version_matches() {
        let spec = std::fs::read_to_string(
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../docs/SPEC.md"),
        )
        .unwrap();
        assert!(
            spec.contains(&format!("**Spec version:** {SPEC_VERSION}")),
            "docs/SPEC.md version line must match api::SPEC_VERSION"
        );
    }
}
